"use client";
import { useState, useMemo } from "react";
import type { TraceReport } from "@/lib/trace/types";
import { Btn, Label, cx } from "./ui";

type ServerTarget = "nextjs" | "nginx" | "cloudflare" | "apache";

interface SecurityHeaderAudit {
  name: string;
  key: string;
  found: boolean;
  currentValue?: string;
  recommendedValue: string;
}

export function SecurityFixGenerator({ report }: { report?: TraceReport }) {
  const [open, setOpen] = useState(false);
  const [target, setTarget] = useState<ServerTarget>("nextjs");
  const [copied, setCopied] = useState(false);
  const [onlyMissing, setOnlyMissing] = useState(true);

  // Analyze the live site's headers from page 0
  const firstHeaders = report?.pages[0]?.headers ?? {};
  const hostname = report?.hostname || "example.com";

  // Discover detected external origins to whitelist in CSP
  const externalDomains = useMemo(() => {
    if (!report?.sources) return [];
    return report.sources.map((s) => s.domain).filter((d) => d && !d.includes(hostname)).slice(0, 8);
  }, [report, hostname]);

  const fontDomains = externalDomains.filter((d) => d.includes("font") || d.includes("typekit") || d.includes("adobe"));
  const scriptDomains = externalDomains.filter((d) => d.includes("analytics") || d.includes("tag") || d.includes("stripe") || d.includes("cdn"));
  const otherDomains = externalDomains.filter((d) => !fontDomains.includes(d) && !scriptDomains.includes(d));

  const scriptSrcList = ["'self'", "'unsafe-inline'", ...scriptDomains.map((d) => `https://${d}`)];
  const styleSrcList = ["'self'", "'unsafe-inline'", ...fontDomains.map((d) => `https://${d}`)];
  const fontSrcList = ["'self'", "data:", ...fontDomains.map((d) => `https://${d}`)];
  const connectSrcList = ["'self'", ...externalDomains.map((d) => `https://${d}`)];
  const imgSrcList = ["'self'", "data:", "https:"];

  const tailoredCsp = `default-src 'self'; script-src ${scriptSrcList.join(" ")}; style-src ${styleSrcList.join(" ")}; img-src ${imgSrcList.join(" ")}; font-src ${fontSrcList.join(" ")}; connect-src ${connectSrcList.join(" ")}; frame-ancestors 'self';`;

  const headerAudits: SecurityHeaderAudit[] = useMemo(() => {
    const check = (key: string, rec: string, displayName: string): SecurityHeaderAudit => {
      const lower = key.toLowerCase();
      const matchKey = Object.keys(firstHeaders).find((k) => k.toLowerCase() === lower);
      const val = matchKey ? firstHeaders[matchKey] : undefined;
      return {
        name: displayName,
        key,
        found: Boolean(val),
        currentValue: val,
        recommendedValue: rec,
      };
    };

    return [
      check("Strict-Transport-Security", "max-age=63072000; includeSubDomains; preload", "HSTS"),
      check("X-Frame-Options", "SAMEORIGIN", "X-Frame-Options"),
      check("X-Content-Type-Options", "nosniff", "X-Content-Type-Options"),
      check("Referrer-Policy", "strict-origin-when-cross-origin", "Referrer-Policy"),
      check("Permissions-Policy", "camera=(), microphone=(), geolocation=()", "Permissions-Policy"),
      check("Content-Security-Policy", tailoredCsp, "Content-Security-Policy"),
    ];
  }, [firstHeaders, tailoredCsp]);

  const activeHeaders = useMemo(() => {
    if (onlyMissing) {
      const missing = headerAudits.filter((h) => !h.found);
      return missing.length > 0 ? missing : headerAudits;
    }
    return headerAudits;
  }, [headerAudits, onlyMissing]);

  const missingCount = headerAudits.filter((h) => !h.found).length;

  const generatedCode = useMemo(() => {
    if (target === "nextjs") {
      const headerObjects = activeHeaders
        .map((h) => `  { key: "${h.key}", value: "${h.recommendedValue.replace(/"/g, '\\"')}" },`)
        .join("\n");

      return `import type { NextConfig } from "next";

// Tailored security headers for ${hostname}
// Auto-generated by TRACE (whitelists ${externalDomains.length} detected external services)
const securityHeaders = [
  { key: "X-DNS-Prefetch-Control", value: "on" },
${headerObjects}
];

const nextConfig: NextConfig = {
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;`;
    }

    if (target === "nginx") {
      const directives = activeHeaders
        .map((h) => `add_header ${h.key} "${h.recommendedValue.replace(/"/g, '\\"')}" always;`)
        .join("\n");

      return `# Tailored Nginx security headers for ${hostname}
# Add inside your server {} or location / {} block:
${directives}`;
    }

    if (target === "cloudflare") {
      const directives = activeHeaders
        .map((h) => `  ${h.key}: ${h.recommendedValue}`)
        .join("\n");

      return `# Cloudflare Pages /_headers configuration for ${hostname}
/*
${directives}`;
    }

    if (target === "apache") {
      const directives = activeHeaders
        .map((h) => `  Header always set ${h.key} "${h.recommendedValue.replace(/"/g, '\\"')}"`)
        .join("\n");

      return `# Apache .htaccess configuration for ${hostname}
<IfModule mod_headers.c>
${directives}
</IfModule>`;
    }

    return "";
  }, [target, activeHeaders, hostname, externalDomains.length]);

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(generatedCode);
      setCopied(true);
      setTimeout(() => setCopied(false), 2200);
    } catch {}
  };

  const fileNames: Record<ServerTarget, string> = {
    nextjs: "next.config.ts",
    nginx: "nginx.conf",
    cloudflare: "_headers",
    apache: ".htaccess",
  };

  return (
    <div className="border border-line bg-panel p-5 space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <div className="flex items-center gap-2">
            <Label className="text-accent">Dynamic Security Header Hardening</Label>
            <span
              className={cx(
                "border px-1.5 py-0.5 font-mono text-[10px]",
                missingCount > 0
                  ? "border-warn/40 bg-warn/10 text-warn"
                  : "border-ok/40 bg-ok/10 text-ok"
              )}
            >
              {missingCount > 0 ? `${missingCount} Missing Headers` : "All Headers Active"}
            </span>
          </div>
          <p className="mt-1 text-xs text-mute">
            Custom-built configuration tailored specifically to <span className="font-mono text-fg">{hostname}</span>. Whitelists detected origins without breaking your scripts.
          </p>
        </div>
        <Btn variant="primary" onClick={() => setOpen(!open)}>
          {open ? "Hide generator" : "Generate tailored fix"}
        </Btn>
      </div>

      {/* Header Audit Pill Summary */}
      <div className="flex flex-wrap gap-1.5 pt-1">
        {headerAudits.map((h) => (
          <span
            key={h.key}
            className={cx(
              "flex items-center gap-1 border px-2 py-0.5 font-mono text-[10px]",
              h.found
                ? "border-ok/30 bg-ok/5 text-ok"
                : "border-bad/30 bg-bad/5 text-bad"
            )}
          >
            <span>{h.found ? "✓" : "✗"}</span>
            <span>{h.name}</span>
          </span>
        ))}
      </div>

      {open && (
        <div className="border border-line bg-bg p-4 space-y-4">
          <div className="flex flex-wrap items-center justify-between gap-3 border-b border-line pb-3">
            {/* Target Selectors */}
            <div className="flex flex-wrap gap-1">
              {(["nextjs", "nginx", "cloudflare", "apache"] as ServerTarget[]).map((k) => (
                <button
                  key={k}
                  onClick={() => setTarget(k)}
                  className={cx(
                    "border px-2.5 py-1 font-mono text-[10px] uppercase tracking-wider transition",
                    target === k
                      ? "border-accent bg-accent/15 text-accent"
                      : "border-line text-mute hover:text-fg"
                  )}
                >
                  {k === "nextjs"
                    ? "Next.js"
                    : k === "nginx"
                    ? "Nginx"
                    : k === "cloudflare"
                    ? "Cloudflare"
                    : "Apache"}
                </button>
              ))}
            </div>

            {/* Scope Filter & Copy */}
            <div className="flex flex-wrap items-center gap-2">
              <label className="flex items-center gap-1.5 font-mono text-[11px] text-mute cursor-pointer">
                <input
                  type="checkbox"
                  checked={onlyMissing}
                  onChange={(e) => setOnlyMissing(e.target.checked)}
                  className="accent-accent"
                />
                <span>Only missing ({missingCount})</span>
              </label>

              <span className="font-mono text-[11px] text-dim">{fileNames[target]}</span>
              <Btn onClick={copy}>{copied ? "Copied! ✓" : "Copy snippet"}</Btn>
            </div>
          </div>

          {/* Generated Code Area */}
          <pre className="max-h-96 overflow-x-auto border border-line bg-panel p-3 font-mono text-xs leading-relaxed text-fg/90">
            <code>{generatedCode}</code>
          </pre>

          {/* Context Explanations */}
          <div className="grid gap-3 sm:grid-cols-2 text-[11px] text-mute border-t border-line pt-3">
            <div>
              <span className="font-mono font-medium text-fg">Domain Whitelist: </span>
              {externalDomains.length > 0
                ? `Automatically included ${externalDomains.slice(0, 4).join(", ")} in connect/script sources.`
                : "No external third-party origins detected."}
            </div>
            <div>
              <span className="font-mono font-medium text-fg">Clickjacking Defense: </span>
              Configured with <span className="font-mono">X-Frame-Options: SAMEORIGIN</span> and CSP frame-ancestors.
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
